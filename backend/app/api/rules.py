@router.get("", response_model=List[RuleOut])
async def list_rules(
    rule_type: Optional[str] = None,
    is_active: Optional[bool] = None,
    db: AsyncSession = Depends(get_db),
):
    stmt = select(Rule).order_by(Rule.id)
    if rule_type:
        stmt = stmt.where(Rule.rule_type == rule_type)
    if is_active is not None:
        stmt = stmt.where(Rule.is_active == is_active)
    result = await db.execute(stmt)
    rules = result.scalars().all()
    provisioned = await _provisioned_sensor_types(db)
    return [_rule_out(r, provisioned) for r in rules]


@router.post("", response_model=RuleOut, status_code=201)
async def create_rule(data: RuleCreate, db: AsyncSession = Depends(get_db)):
    err = _validate_rule_payload(
        data.rule_type, data.sensor_type, data.operator,
        data.threshold_value, data.dtc_code, data.interval_value,
    )
    if err:
        raise HTTPException(status_code=422, detail=err)
    rule = Rule(**data.model_dump())
    db.add(rule)
    await db.flush()
    invalidate_rules_cache()
    return _rule_out(rule, await _provisioned_sensor_types(db))


@router.get("/{rule_id}", response_model=RuleOut)
async def get_rule(rule_id: int, db: AsyncSession = Depends(get_db)):
    result = await db.execute(select(Rule).where(Rule.id == rule_id))
    rule = result.scalar_one_or_none()
    if not rule:
        raise HTTPException(status_code=404, detail="Rule not found")
    return _rule_out(rule, await _provisioned_sensor_types(db))


@router.patch("/{rule_id}", response_model=RuleOut)
async def update_rule(rule_id: int, data: RuleUpdate, db: AsyncSession = Depends(get_db)):
    result = await db.execute(select(Rule).where(Rule.id == rule_id))
    rule = result.scalar_one_or_none()
    if not rule:
        raise HTTPException(status_code=404, detail="Rule not found")
    for k, v in data.model_dump(exclude_unset=True).items():
        setattr(rule, k, v)
    err = _validate_rule_payload(
        rule.rule_type, rule.sensor_type, rule.operator,
        rule.threshold_value, rule.dtc_code, rule.interval_value,
    )
    if err:
        raise HTTPException(status_code=422, detail=err)
    await db.flush()
    invalidate_rules_cache()
    return _rule_out(rule, await _provisioned_sensor_types(db))


@router.delete("/{rule_id}", status_code=204)
async def delete_rule(rule_id: int, db: AsyncSession = Depends(get_db)):
    result = await db.execute(select(Rule).where(Rule.id == rule_id))
    rule = result.scalar_one_or_none()
    if not rule:
        raise HTTPException(status_code=404, detail="Rule not found")
    await db.delete(rule)
    invalidate_rules_cache()