"""
PREDICT — Rules & Work Order Templates API
CRUD for rules and templates used by the rule engine.
Mutations invalidate the engine's in-process rule cache.
"""
from typing import List, Optional

from fastapi import APIRouter, Depends, HTTPException, Query
from sqlalchemy import func, select
from sqlalchemy.ext.asyncio import AsyncSession

from app.db.database import get_db
from app.db.models import Rule, RuleType, Sensor, WorkOrderTemplate
from app.rules.engine import (
    BEHAVIOR_EVENT_TYPES,
    SCHEDULED_SENSOR_TYPES,
    OPERATORS,
    invalidate_rules_cache,
)
from app.schemas.schemas import (
    RuleCreate,
    RuleOut,
    RuleUpdate,
    WorkOrderTemplateCreate,
    WorkOrderTemplateOut,
)

router = APIRouter(prefix="/rules", tags=["rules"])


def _validate_rule_payload(rule_type, sensor_type, operator, threshold_value,
                           dtc_code, interval_value) -> Optional[str]:
    """Return an error message when the rule can never evaluate, else None."""
    if rule_type in (RuleType.THRESHOLD, "threshold"):
        if not sensor_type:
            return "Threshold rules require sensor_type"
        if operator not in OPERATORS:
            return f"Operator must be one of {sorted(OPERATORS)}"
        if threshold_value is None:
            return "Threshold rules require threshold_value"
    elif rule_type in (RuleType.DTC, "dtc"):
        if not dtc_code:
            return "DTC rules require dtc_code"
    elif rule_type in (RuleType.SCHEDULED, "scheduled"):
        if sensor_type not in SCHEDULED_SENSOR_TYPES:
            return f"Scheduled rules require sensor_type in {SCHEDULED_SENSOR_TYPES}"
        if not interval_value or interval_value <= 0:
            return "Scheduled rules require a positive interval_value"
    elif rule_type in (RuleType.BEHAVIOR, "behavior"):
        if sensor_type not in BEHAVIOR_EVENT_TYPES:
            return f"Behavior rules require sensor_type (event) in {BEHAVIOR_EVENT_TYPES}"
        if threshold_value is None:
            return "Behavior rules require threshold_value (event count)"
        if operator and operator not in OPERATORS:
            return f"Operator must be one of {sorted(OPERATORS)}"
    elif rule_type in (RuleType.ANOMALY, "anomaly"):
        return "Anomaly rules are auto-generated by the baselines job"
    return None


async def _provisioned_sensor_types(db: AsyncSession) -> set:
    result = await db.execute(select(Sensor.sensor_type).distinct())
    return {row[0] for row in result.all()}


def _rule_out(rule: Rule, provisioned: set) -> RuleOut:
    dormant = bool(
        rule.is_active
        and rule.rule_type in (RuleType.THRESHOLD, RuleType.SCHEDULED)
        and rule.sensor_type
        and rule.sensor_type not in provisioned
    )
    out = RuleOut.model_validate(rule)
    out.dormant = dormant
    return out


